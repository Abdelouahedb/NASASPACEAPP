"""Step 5 - bundle everything the web app needs into web/data/data.js

    python scripts/05_export.py
"""
import csv
import json
from datetime import date

import numpy as np

import config as C


def load_official():
    p = C.DATA / "official_fill.csv"
    if not p.exists():
        return []
    with open(p, encoding="utf-8") as f:
        return [{"date": r["date"], "fill_pct": float(r["fill_pct"]),
                 "volume_mm3": float(r["volume_mm3"]) if r["volume_mm3"] else None,
                 "source": r["source"], "url": r["url"]} for r in csv.DictReader(f)]


def interp(official, d, field):
    pts = [(date.fromisoformat(o["date"]).toordinal(), o[field]) for o in official if o[field] is not None]
    if not pts:
        return None
    xs, ys = zip(*pts)
    return float(np.interp(date.fromisoformat(d).toordinal(), xs, ys))


def main():
    zones = {}
    for z in C.ZONES:
        p = C.zone_paths(z)["json"]
        if p.exists():
            zones[z] = json.loads(p.read_text(encoding="utf-8"))
        else:
            print(f"(no {z}.json yet - run step 3/4 for it)")
    official = load_official()

    budget = None
    lake = zones.get("massira")
    if lake and official:
        full = [d for d in lake["dates"] if not d["partial"]]
        a, b = full[0], full[-1]
        va, vb = interp(official, a["date"], "volume_mm3"), interp(official, b["date"], "volume_mm3")
        budget = {
            "from": a["date"], "to": b["date"],
            "lake_km2_from": a["lake_km2"], "lake_km2_to": b["lake_km2"],
            "volume_mm3_from": round(va, 1), "volume_mm3_to": round(vb, 1),
            "fill_from": round(interp(official, a["date"], "fill_pct"), 2),
            "fill_to": round(interp(official, b["date"], "fill_pct"), 2),
        }
    fields = zones.get("doukkala")
    if budget and fields:
        budget["crop_km2"] = fields["classes"]["crop"]["km2"]

    payload = {
        "generated": date.today().isoformat(),
        "demo": any(z.get("demo") for z in zones.values()),
        "zones": zones,
        "official": official,
        "budget": budget,
        "dam": [32.4753, -7.6375],
    }
    C.WEB_DATA.mkdir(parents=True, exist_ok=True)
    out = C.WEB_DATA / "data.js"
    out.write_text("// generated by scripts/05_export.py\nwindow.NABD = " + json.dumps(payload) + ";\n",
                   encoding="utf-8")
    print(f"wrote {out} ({out.stat().st_size / 1e3:.0f} kB). Open web/index.html")


if __name__ == "__main__":
    main()
